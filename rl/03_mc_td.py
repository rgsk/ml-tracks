"""
Monte Carlo & TD(0) PREDICTION — drop the known model, estimate V^π from SAMPLED
experience. This is the first model-FREE method: the agent may only RESET and STEP
the world, it never gets to read p(s'|s,a) or r(s,a,s').

Recall exercise 2: with the model in hand, policy_evaluation just swept the Bellman
expectation backup (or you literally solved V = (I-γPπ)⁻¹rπ). That required knowing
P and r for every (s,a). Real agents almost never have that. All they have is a
stream of transitions (s, r, s'), generated by acting. So: how do you estimate the
value of a fixed policy π from samples alone?

TWO ANSWERS, and the bias/variance trade-off that splits them:

  MONTE CARLO (MC) — wait until the episode ENDS, then look at the actual return
    G_t = r_{t+1} + γ r_{t+2} + ... + γ^{T-1-t} r_T
  and average G_t over every time you visited state s. No bootstrapping, no model.
    V(s) ≈ average of observed returns from s.
  UNBIASED (G_t is a real sample of the true return) but HIGH VARIANCE — G_t
  depends on the whole tail of the episode (every random action and slip). And you
  must wait for termination, so no learning on never-ending tasks.

  TD(0) — don't wait. After a SINGLE step you already have a guess of the rest:
  V(s') itself. Bootstrap off it.
    target = r + γ V(s')            (the "TD target")
    V(s) <- V(s) + α [ r + γ V(s') - V(s) ]
  The bracket is the TD ERROR δ — exactly the (sample − prediction) nudge shape from
  the bandit update, now with a bootstrapped sample. BIASED (V(s') is your own
  current, wrong estimate) but LOW VARIANCE (one reward + one estimate, not a whole
  tail) and it learns ONLINE, step by step. This bootstrap is the seed of
  Q-learning / SARSA / DQN later.

So: MC ↔ TD(0) is the first appearance of the "bias/variance of the target" thread.
n-step and GAE(λ) later interpolate between these two extremes.

WHAT WE PREDICT: the value of the OPTIMAL policy from exercise 2. Satisfying
tie-back — MC and TD recover V* from samples alone, no model — and it gives us an
exact ground truth (the analytic linear solve) to grade your estimates against.

EXPLORING STARTS: a deterministic policy from a fixed start would only ever trace
one path, leaving most of the grid unvisited (and thus unestimated). So each
episode begins at a RANDOM non-terminal state — the simplest way to guarantee every
state's value gets sampled. (Real control fixes this differently, via ε-greedy
behaviour; that's exercise 4.)

ENV: the exercise-2 gridworld, imported and wrapped in a gym-like Sampler exposing
only reset()/step(a). The model P is still in there, but the algorithms below never
touch it — that's the whole point.
"""

from __future__ import annotations

import importlib.util
import pathlib

import numpy as np

# Import GridWorld + the exact ground-truth solver from exercise 2. (Module name
# starts with a digit, so a normal `import` won't parse — load it by path.)
_spec = importlib.util.spec_from_file_location(
    "mdp_dp", pathlib.Path(__file__).with_name("02_mdp_dp.py"))
mdp_dp = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(mdp_dp)
GridWorld = mdp_dp.GridWorld


class Sampler:
    """Gym-like wrapper that turns the MDP model into an EXPERIENCE stream.

    The DP algorithms in exercise 2 read env.P directly. The model-free algorithms
    here may only call reset()/step(a) — they see transitions, never probabilities.
    (Internally we sample from env.P; the algorithms just don't get to look.)
    """

    def __init__(self, env: GridWorld, rng: np.random.Generator):
        self.env = env
        self.rng = rng
        self._nonterminal = [s for s, cell in enumerate(env.states)
                             if cell not in env.terminals]
        self.s = None

    def reset(self) -> int:
        """Exploring start: begin at a uniformly random NON-terminal state."""
        self.s = int(self.rng.choice(self._nonterminal))
        return self.s

    def step(self, a):
        """One sampled transition from the current state. Returns (s', r, done).

        The ENV rolls its OWN dice — which action actually fires after the slip —
        then applies deterministic movement. It never builds a probability table;
        the agent just sees the single (s', r) that falls out. (Reuses the same
        _move + noise that exercise 2's model was built from, so the sampled
        dynamics match env.P exactly — by construction, not by luck.)
        """
        env = self.env
        cell = env.states[self.s]
        # slip: intended action w.p. 1-noise, each perpendicular w.p. noise/2.
        actual = int(self.rng.choice([a, (a + 1) % 4, (a - 1) % 4],
                                     p=[1 - env.noise, env.noise / 2, env.noise / 2]))
        nxt = env._move(cell, actual)            # wall/edge bounce lives in _move
        reward = env.terminals.get(nxt, env.step_reward)
        done = nxt in env.terminals
        self.s = env.s2i[nxt]
        return self.s, reward, done


