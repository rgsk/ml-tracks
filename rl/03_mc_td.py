def rms_error(V_hat: np.ndarray, V_true: np.ndarray,
              nonterminal: list[int]) -> float:
    """Root-mean-square error over the NON-terminal states (terminals are trivially
    0 for everyone and would only dilute the metric)."""
    diff = V_hat[nonterminal] - V_true[nonterminal]
    return float(np.sqrt(np.mean(diff ** 2)))


def render_values(env: GridWorld, V: np.ndarray) -> str:
    grid = [["  ·  " for _ in range(env.cols)] for _ in range(env.rows)]
    for (r, c) in env.walls:
        grid[r][c] = "  #  "
    for s, cell in enumerate(env.states):
        grid[cell[0]][cell[1]] = f"{V[s]:+.2f}"
    return "\n".join(" ".join(row) for row in grid)


if __name__ == "__main__":
    env = GridWorld()
    g = env.gamma
    rng = np.random.default_rng(0)
    sampler = Sampler(env, rng)

    # The policy we predict: the OPTIMAL policy from exercise 2's value iteration,
    # plus its EXACT value via the linear solve — our ground truth.
    opt_policy, _ = mdp_dp.value_iteration(env, g)
    V_true = mdp_dp.analytic_policy_value(env, opt_policy, g)
    nonterminal = sampler._nonterminal

    # --- 0) generate_episode produces a valid, terminating trajectory ----------
    ep = generate_episode(sampler, opt_policy, rng)
    assert len(ep) > 0, "episode should have at least one transition"
    assert ep[-1][3] is True or ep[-1][3] == 1, \
        "a finished episode's last transition should have done=True"
    assert all(0 <= s < env.nS and 0 <= ns < env.nS for (s, _r, ns, _d) in ep), \
        "episode visited an out-of-range state"
    assert env.states[ep[0][0]] not in env.terminals, \
        "exploring start should not begin on a terminal state"
    print(f"generate_episode rolls out a valid episode (len {len(ep)}) ✅")

    # --- 1) Monte Carlo prediction converges to the true V^π -------------------
    V_mc = mc_prediction(env, sampler, opt_policy, g, num_episodes=20000, rng=rng)
    err_mc = rms_error(V_mc, V_true, nonterminal)
    assert err_mc < 0.05, f"MC RMS error too high: {err_mc:.4f}"
    print(f"first-visit MC matches the analytic V^π  (RMS {err_mc:.4f}) ✅")

    # --- 2) TD(0) prediction converges to the true V^π -------------------------
    V_td = td0_prediction(env, sampler, opt_policy, g,
                          num_episodes=20000, alpha=0.05, rng=rng)
    err_td = rms_error(V_td, V_true, nonterminal)
    # looser bound than MC on purpose: constant-alpha TD doesn't converge to zero
    # error, it hovers around the truth (the step never shrinks) — that's expected.
    assert err_td < 0.07, f"TD(0) RMS error too high: {err_td:.4f}"
    print(f"TD(0) matches the analytic V^π            (RMS {err_td:.4f}) ✅")

    # --- 3) both model-free estimates agree with each other --------------------
    assert rms_error(V_mc, V_td, nonterminal) < 0.07, \
        "MC and TD(0) should land on the same V^π"
    print("MC and TD(0) agree (both recover V* from samples, no model) ✅")

    print("\nground truth V^π (optimal policy):")
    print(render_values(env, V_true))
    print("\nMonte Carlo estimate:")
    print(render_values(env, V_mc))
    print("\nTD(0) estimate:")
    print(render_values(env, V_td))
    print("\nmodel-free prediction works ✅")
