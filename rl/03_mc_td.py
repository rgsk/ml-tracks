def generate_episode(sampler: Sampler, policy: np.ndarray,
                     rng: np.random.Generator,
                     max_steps: int = 1000) -> list[tuple[int, float, int, bool]]:
    """Roll out ONE episode following `policy`; return the raw experience both
    predictors learn from, as a list of transitions:

        [(s, r, s_next, done), ...]    one per step, in time order.

    `policy` is a stochastic matrix (nS, nA); sample the action a ~ policy[s].
    Start from sampler.reset(); stop when step() reports done (or max_steps hit).
    """
    episode = []
    s = sampler.reset()
    for _ in range(max_steps):
        a = int(rng.choice(sampler.env.nA, p=policy[s]))
        ns, r, done = sampler.step(a)
        episode.append((s, r, ns, done))
        s = ns
        if done:
            break
    return episode


def returns_from_episode(episode, gamma):
    """Discounted return G_t for every step, via one O(T) backward sweep.
    Returns a list aligned with `episode`: returns[t] is the return of state s_t."""
    G = 0.0
    out = [0.0] * len(episode)
    for t in range(len(episode) - 1, -1, -1):
        r = episode[t][1]
        G = r + gamma * G
        out[t] = G
    return out


def mc_prediction(env: GridWorld, sampler: Sampler, policy: np.ndarray,
                  gamma: float, num_episodes: int, rng: np.random.Generator,
                  first_visit: bool = True) -> np.ndarray:
    """Monte Carlo prediction of V^π — average observed returns G_t per state.

    Per episode, get every G_t from returns_from_episode (the O(T) backward sweep),
    then credit states. first_visit (default): only the FIRST occurrence of a state
    in the episode contributes — so samples are i.i.d. across episodes and the mean
    is unbiased for every n. first_visit=False is every-visit MC: also consistent,
    biased at finite n (within-episode returns are correlated suffixes).

    Returns V of shape (nS,).
    """
    returns_sum = np.zeros(env.nS)
    returns_cnt = np.zeros(env.nS)
    for _ in range(num_episodes):
        ep = generate_episode(sampler, policy, rng)
        G = returns_from_episode(ep, gamma)
        seen = set()
        for t, (s, _r, _ns, _d) in enumerate(ep):
            if first_visit and s in seen:
                continue                     # first-visit: skip repeat occurrences
            seen.add(s)
            returns_sum[s] += G[t]
            returns_cnt[s] += 1
    V = np.zeros(env.nS)
    nz = returns_cnt > 0
    V[nz] = returns_sum[nz] / returns_cnt[nz]
    return V


def td0_prediction(env: GridWorld, sampler: Sampler, policy: np.ndarray,
                   gamma: float, num_episodes: int, alpha: float,
                   rng: np.random.Generator) -> np.ndarray:
    """TD(0) prediction of V^π with a constant step size alpha.

    For every transition (s, r, s', done):
        target = r + gamma * V(s') * (1 - done)     # bootstrap; 0 past termination
        V(s)  += alpha * (target - V(s))            # the TD-error nudge

    The (1 - done) mask zeroes the bootstrap when s' is terminal — there's no future
    beyond the end. (Here V(terminal) stays 0 anyway, but the mask is the correct,
    general form and matters once V is a learned function.)

    Returns V of shape (nS,).
    """
    V = np.zeros(env.nS)
    for _ in range(num_episodes):
        for (s, r, ns, done) in generate_episode(sampler, policy, rng):
            target = r + gamma * V[ns] * (1.0 - done)   # no bootstrap past the end
            V[s] += alpha * (target - V[s])
    return V


